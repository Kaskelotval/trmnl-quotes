#!/usr/bin/env python3
"""
Generate/refresh data/speakers.json from data/speakers_raw.json
(produced by 0_extract_from_db.py).

Why this exists separately from 0_extract_from_db.py: speakers.json is
meant to be hand-curated over time (portraits, corrected types, merged
duplicates), so this script MERGES rather than overwrites -- rerunning
it after a fresh extraction will not clobber portraits or type fixes
you've already made for slugs that still exist.

Slug strategy: actor names in the DB often carry parenthetical epithets
or trailing clauses, e.g. "Klaasje (Miss Oranje Disco Dancer)" or
"Lena, the Cryptozoologist's wife". The full name is kept in "name";
the id/slug is derived from the text before the first "(" or ",", which
matches how people actually refer to these characters ("klaasje",
"lena"). Collisions (two different actors truncating to the same short
form) get a numeric suffix -- check the printed warnings and rename by
hand if a collision looks wrong.

Only actors flagged "speaks_at_least_once" by 0_extract_from_db.py are
included -- that's computed from actual dentries rows, not the
actors.talkativeness column (which reads 0 for at least 8 actors,
including Perception and its sub-skills, that provably do speak in
this export -- don't trust that column). This naturally excludes ID 0
("HUB", a null join actor) and the abstract stat categories that truly
never appear on a real line (Psyche, Motorics, Intellect, Fysique).

IMPORTANT: Harry (the player character) is NOT a separate actor in this
data -- his lines are recorded under actor id 387, named "You", same
bucket the pipeline treats as generic player dialogue. If you want
Harry's own lines in your corpus, re-run 0_extract_from_db.py with
--include-player and expect the resulting quotes to use speaker id "you".

Usage:
    python3 build_speaker_registry.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA_DIR = HERE / "data"
RAW_SPEAKERS = DATA_DIR / "speakers_raw.json"
OUT = HERE.parent / "sources" / "disco-elysium" / "quotes" / "speakers.json"


def short_slug(name: str) -> str:
    """'Klaasje (Miss Oranje Disco Dancer)' -> 'klaasje'
       'Lena, the Cryptozoologist's wife'   -> 'lena'
       'Kim Kitsuragi'                       -> 'kim_kitsuragi'"""
    base = re.split(r"[,(]", name, maxsplit=1)[0].strip()
    slug = re.sub(r"[^a-z0-9]+", "_", base.lower()).strip("_")
    return slug or "unknown"


def main():
    if not RAW_SPEAKERS.exists():
        raise SystemExit(
            f"ERROR: {RAW_SPEAKERS} not found. Run 0_extract_from_db.py first."
        )

    raw = json.loads(RAW_SPEAKERS.read_text(encoding="utf-8"))
    existing = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    # keep the human-readable _readme key if present, drop it from the merge logic
    existing.pop("_readme", None)

    slug_counts = {}
    registry = {}

    for actor_id, info in raw.items():
        name = info["name"]
        actor_type = info["type"]
        if actor_type == "hub":
            continue  # never a real speaker
        if not info.get("speaks_at_least_once", False):
            continue  # ground-truth check against dentries, not talkativeness

        base_slug = short_slug(name)
        slug_counts[base_slug] = slug_counts.get(base_slug, 0) + 1
        slug = base_slug if slug_counts[base_slug] == 1 else f"{base_slug}_{slug_counts[base_slug]}"

        prior = existing.get(slug, {})
        registry[slug] = {
            "name": name,
            "type": prior.get("type", actor_type),  # preserve manual type fixes
            "image": prior.get("image"),             # preserve portraits you've set
            "actor_id": int(actor_id),
        }

    # report collisions worth a manual look
    collisions = {s: n for s, n in slug_counts.items() if n > 1}
    if collisions:
        print("Slug collisions (auto-suffixed, worth checking by hand):")
        for slug, n in collisions.items():
            print(f"  {slug}: {n} actors share this short name")

    payload = {
        "_readme": "Generated by pipeline/build_speaker_registry.py from the real "
                   "disco.db actor table, then merged with any portraits/type "
                   "overrides you've already set. Safe to rerun -- it will not "
                   "erase your edits for slugs that still exist. Add 'image' "
                   "paths as you prepare portraits.",
    }
    payload.update(dict(sorted(registry.items())))

    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(registry)} speakers -> {OUT}")


if __name__ == "__main__":
    main()
